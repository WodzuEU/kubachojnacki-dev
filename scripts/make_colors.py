"""Colour data for every painting, for sorting and filtering by colour.

    python scripts/make_colors.py

Reads IMAGES/thumbs/<slug>.webp (400px) for each slug in js/data.js,
ignores the white photo background, and writes js/colors.js:

    COLORS["<slug>"] = { hex, hue, sat, light, family, swatches: [hex, ...] }

hue 0-360, sat/light 0-1 (HSL of the dominant colour), family = one word
(violet, blue, green, yellow, orange, red, pink, brown, grey, dark, light),
swatches = up to 5 main colours, most area first. Re-run after adding works.
"""
import colorsys, json, os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
data = open(os.path.join(ROOT, "js", "data.js"), encoding="utf-8").read()
slugs = re.findall(r'slug:\s*"([^"]+)"', data)


def hexof(rgb):
    return "#%02x%02x%02x" % tuple(int(c) for c in rgb)


def family(h, s, l):
    if l < 0.16:
        return "dark"
    if s < 0.14:
        return "light" if l > 0.75 else "grey"
    if 15 <= h < 45 and l < 0.5:
        return "brown"
    for top, name in ((15, "red"), (45, "orange"), (70, "yellow"), (165, "green"),
                      (245, "blue"), (290, "violet"), (335, "pink"), (361, "red")):
        if h < top:
            return name


out = {}
for slug in dict.fromkeys(slugs):
    path = os.path.join(ROOT, "IMAGES", "thumbs", slug + ".webp")
    if not os.path.exists(path):
        continue
    im = Image.open(path).convert("RGB")
    im.thumbnail((160, 160))
    px = []
    for r, g, b in (im.get_flattened_data() if hasattr(im, "get_flattened_data") else im.getdata()):
        hh, ll, ss = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
        if ll > 0.9 and ss < 0.35:      # white wall / photo background
            continue
        px.append((r, g, b))
    if not px:
        continue
    strip = Image.new("RGB", (len(px), 1))
    strip.putdata(px)
    q = strip.quantize(colors=5, method=Image.Quantize.MEDIANCUT)
    pal = q.getpalette()[:15]
    counts = sorted(q.getcolors(), reverse=True)
    sw = [tuple(pal[i * 3:i * 3 + 3]) for _, i in counts]
    # the dominant colour = the average of all painted pixels, kept for hue order
    avg = tuple(sum(c[k] for c in px) / len(px) for k in range(3))
    h, l, s = colorsys.rgb_to_hls(*(c / 255 for c in avg))
    # hue from the most saturated large swatch, so a dark blue painting reads blue
    best = max(sw[:3], key=lambda c: colorsys.rgb_to_hls(*(x / 255 for x in c))[2])
    bh, bl, bs = colorsys.rgb_to_hls(*(x / 255 for x in best))
    hue = round((bh if bs > 0.12 else h) * 360)
    out[slug] = {
        "hex": hexof(avg), "hue": hue, "sat": round(s, 3), "light": round(l, 3),
        "family": family(hue, bs if bs > 0.12 else s, (bl + l) / 2),
        "swatches": [hexof(c) for c in sw],
    }

with open(os.path.join(ROOT, "js", "colors.js"), "w", encoding="utf-8") as f:
    f.write("/* generated by scripts/make_colors.py — do not edit by hand */\n")
    f.write("const COLORS = " + json.dumps(out, indent=1) + ";\n")
print(len(out), "works ->", "js/colors.js")
fam = {}
for s, v in out.items():
    fam.setdefault(v["family"], []).append(s.split("-", 2)[2] if s.count("-") >= 2 else s)
for k, v in sorted(fam.items()):
    print(f"{k:7} {len(v):2}  " + ", ".join(v[:8]))
